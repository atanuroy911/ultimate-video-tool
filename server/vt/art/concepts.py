"""Hand-built colour clipart for ideas that have no emoji: space, physics, biology, abstract science.

Each drawing is generated by code (flat colours, soft glows, a few hundred bytes of maths per shape) in the same square 128 x 128 frame the emoji use,
so it can sit anywhere an emoji sticker can: sticker, feature card, cartoon prop, pictogram. Everything is original work, free to use in any video.
`KEYS` maps the id ("art-black-hole") to its drawing; `WORDS` maps the words people say to an id.
"""
from __future__ import annotations

import math
import random
from typing import Callable

V = 'viewBox="0 0 128 128" xmlns="http://www.w3.org/2000/svg"'


def _stars(seed: int, n: int, r0: float, cx: float = 64, cy: float = 64, rmax: float = 58) -> str:
    rnd = random.Random(seed)
    out = []
    for _ in range(n):
        a, d = rnd.uniform(0, 2 * math.pi), rmax * math.sqrt(rnd.random())
        out.append(f'<circle cx="{cx + d * math.cos(a):.1f}" cy="{cy + d * math.sin(a):.1f}" r="{rnd.uniform(r0 * 0.5, r0):.2f}" fill="#fff" opacity="{rnd.uniform(0.5, 1):.2f}"/>')
    return "".join(out)


def _space_disc(inner: str = "#1b1f4b", outer: str = "#070816") -> str:
    return (f'<defs><radialGradient id="sp" cx="50%" cy="45%" r="60%"><stop offset="0" stop-color="{inner}"/><stop offset="1" stop-color="{outer}"/></radialGradient></defs>'
            '<circle cx="64" cy="64" r="60" fill="url(#sp)"/>')


def black_hole() -> str:
    return (f'<svg {V}><defs>'
            '<radialGradient id="g1" cx="50%" cy="50%" r="50%"><stop offset="0.55" stop-color="#ffb347" stop-opacity="0"/><stop offset="0.75" stop-color="#ff8a3d" stop-opacity=".85"/><stop offset="1" stop-color="#ff5a36" stop-opacity="0"/></radialGradient>'
            '<linearGradient id="g2" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#ff7a3d"/><stop offset=".5" stop-color="#ffe29a"/><stop offset="1" stop-color="#ff7a3d"/></linearGradient>'
            '<radialGradient id="sp" cx="50%" cy="45%" r="60%"><stop offset="0" stop-color="#241a4d"/><stop offset="1" stop-color="#070816"/></radialGradient></defs>'
            '<circle cx="64" cy="64" r="60" fill="url(#sp)"/>' + _stars(3, 26, 1.3) +
            '<circle cx="64" cy="64" r="44" fill="url(#g1)"/>'
            '<ellipse cx="64" cy="66" rx="52" ry="12" fill="none" stroke="url(#g2)" stroke-width="7" opacity=".95" transform="rotate(-14 64 66)"/>'
            '<circle cx="64" cy="64" r="21" fill="#000"/>'
            '<path d="M43 64a21 21 0 0 1 42 0" fill="none" stroke="#ffe9b0" stroke-width="2.4" opacity=".9"/>'
            '<ellipse cx="64" cy="66" rx="52" ry="12" fill="none" stroke="url(#g2)" stroke-width="7" stroke-dasharray="0 78 82 200" transform="rotate(-14 64 66)"/></svg>')


def galaxy() -> str:
    parts = [_space_disc("#2a1c5c", "#080818"), _stars(7, 34, 1.2)]
    for arm in (0, math.pi):
        for i in range(70):
            t = i / 69
            a = arm + t * 3.6 * math.pi * 0.62
            r = 6 + t * 46
            x, y = 64 + r * math.cos(a), 64 + r * math.sin(a) * 0.62
            col = ("#ffd6f5", "#c9a8ff", "#7aa7ff")[min(2, int(t * 3))]
            parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{3.2 - 1.6 * t:.2f}" fill="{col}" opacity="{0.95 - 0.5 * t:.2f}"/>')
    parts.append('<ellipse cx="64" cy="64" rx="13" ry="9" fill="#fff3c8" opacity=".95"/><ellipse cx="64" cy="64" rx="22" ry="14" fill="#ffd27a" opacity=".35"/>')
    return f'<svg {V}>' + "".join(parts) + "</svg>"


def nebula() -> str:
    blobs = [(44, 52, 26, "#ff5fa2", .55), (78, 46, 24, "#7b61ff", .6), (66, 78, 28, "#2ec5ff", .45), (50, 82, 18, "#ffb347", .4), (86, 76, 16, "#ff5fa2", .4)]
    return (f'<svg {V}>' + _space_disc("#1a1440", "#06060f") + '<defs><filter id="bl"><feGaussianBlur stdDeviation="7"/></filter></defs><g filter="url(#bl)">' +
            "".join(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{c}" opacity="{o}"/>' for x, y, r, c, o in blobs) + "</g>" + _stars(11, 38, 1.4) + "</svg>")


def supernova() -> str:
    rays = "".join(f'<path d="M64 64 L{64 + 58 * math.cos(a):.1f} {64 + 58 * math.sin(a):.1f}" stroke="#ffb347" stroke-width="{3 if i % 2 else 5}" stroke-linecap="round" opacity=".9"/>'
                   for i, a in enumerate(k * math.pi / 8 for k in range(16)))
    return (f'<svg {V}>' + _space_disc("#3a1450", "#0a0618") + rays +
            '<circle cx="64" cy="64" r="34" fill="#ff6a3d"/><circle cx="64" cy="64" r="25" fill="#ffb347"/><circle cx="64" cy="64" r="15" fill="#fff3c8"/></svg>')


def atom() -> str:
    orb = "".join(f'<ellipse cx="64" cy="64" rx="56" ry="20" fill="none" stroke="#3b82f6" stroke-width="4.5" transform="rotate({a} 64 64)"/>' for a in (0, 60, 120))
    els = "".join(f'<circle cx="{64 + 56 * math.cos(math.radians(t)):.1f}" cy="{64 + 20 * math.sin(math.radians(t)):.1f}" r="6" fill="#ff7a3d" transform="rotate({a} 64 64)"/>'
                  for a, t in ((0, 20), (60, 200), (120, 110)))
    return f'<svg {V}>{orb}{els}<circle cx="64" cy="64" r="12" fill="#ef4444"/><circle cx="59" cy="60" r="4" fill="#fff" opacity=".5"/></svg>'


def dna() -> str:
    parts = []
    for i in range(14):
        t = i / 13
        y = 12 + t * 104
        x1 = 64 + 34 * math.sin(t * 2.5 * math.pi)
        x2 = 128 - x1
        z = math.cos(t * 2.5 * math.pi)
        parts.append(f'<line x1="{x1:.1f}" y1="{y:.1f}" x2="{x2:.1f}" y2="{y:.1f}" stroke="{"#fbbf24" if i % 2 else "#34d399"}" stroke-width="4" opacity=".85"/>')
        for x, col in ((x1, "#3b82f6"), (x2, "#ec4899")):
            parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{6.5 + 1.5 * z * (1 if col == "#3b82f6" else -1):.1f}" fill="{col}"/>')
    return f'<svg {V}>' + "".join(parts) + "</svg>"


