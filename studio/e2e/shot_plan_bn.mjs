import { chromium } from "playwright-core";
import { base, chromePath } from "./common.mjs";
const b = await chromium.launch({ executablePath: chromePath() });
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addInitScript(() => localStorage.setItem("vt-lang", "bn"));
const page = await ctx.newPage();
await fetch(base + "/api/projects/reference/plan/make", { method: "POST", headers: { "content-type": "application/json" }, body: "{}" });
await fetch(base + "/api/settings", { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify({ ui_language: "bn" }) });
await page.goto(`${base}/p/reference`, { waitUntil: "domcontentloaded" });
await page.getByRole("button", { name: "এআই", exact: true }).click();
await page.getByTestId("reel-plan").click();
await page.getByRole("dialog").waitFor();
await page.waitForTimeout(600);
await page.screenshot({ path: "e2e/out/plan/bn-step1.png" });
await page.locator(".ios-foot .btn.primary").click();
await page.locator(".ios-foot .btn.primary").click();
await page.waitForTimeout(500);
await page.screenshot({ path: "e2e/out/plan/bn-step3.png" });
await fetch(base + "/api/settings", { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify({ ui_language: "en" }) });
await b.close();
