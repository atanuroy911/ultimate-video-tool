const dicts = { en, bn };

export function useT() {
  const lang = useStore(settingsStore).ui_language;
  return (key: string): string => dicts[lang][key] ?? en[key] ?? key;
}

export function setLanguage(l: "en" | "bn") {
  localStorage.setItem("vt-lang", l);
  settingsStore.set((s) => ({ ...s, ui_language: l }));
  document.documentElement.lang = l;
}
