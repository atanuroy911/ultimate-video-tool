def pulsar() -> str:
    beams = '<path d="M64 64L26 28M64 64L102 100" stroke="#7dd3fc" stroke-width="14" stroke-linecap="round" opacity=".35"/><path d="M64 64L26 28M64 64L102 100" stroke="#e0f2fe" stroke-width="5" stroke-linecap="round"/>'
    return f'<svg {V}>' + _space_disc("#16224d", "#050612") + beams + '<circle cx="64" cy="64" r="15" fill="#dbeafe"/><circle cx="64" cy="64" r="22" fill="#60a5fa" opacity=".4"/></svg>'


def wave() -> str:
    d = " ".join(f'{"M" if i == 0 else "L"}{8 + i * 3:.0f} {64 - 34 * math.sin(i / 39 * 4 * math.pi) * math.sin(i / 39 * math.pi) ** 0.5:.1f}' for i in range(41))
    return f'<svg {V}><path d="{d}" fill="none" stroke="#6366f1" stroke-width="8" stroke-linecap="round" stroke-linejoin="round"/><path d="{d}" fill="none" stroke="#a5b4fc" stroke-width="3" transform="translate(0 -3)" stroke-linecap="round"/></svg>'


def prism() -> str:
    cols = ("#ef4444", "#f59e0b", "#facc15", "#22c55e", "#3b82f6", "#8b5cf6")
    rays = "".join(f'<path d="M74 60L124 {22 + i * 15}" stroke="{c}" stroke-width="7" stroke-linecap="round"/>' for i, c in enumerate(cols))
    return f'<svg {V}>{rays}<path d="M8 66L66 62" stroke="#fff" stroke-width="7" stroke-linecap="round" opacity=".9"/><path d="M52 98L64 28l24 70z" fill="#bfdbfe" fill-opacity=".8" stroke="#60a5fa" stroke-width="3" stroke-linejoin="round"/></svg>'


