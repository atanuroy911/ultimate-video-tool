// Builds design/fonts/ (woff2 + fonts.css) from @fontsource packages.
// Only Bengali + Latin subsets are kept so every theme can mix Bangla and English.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const out = path.resolve(root, "..", "design", "fonts");
fs.mkdirSync(out, { recursive: true });

const FAMILIES = [
  { pkg: "hind-siliguri", weights: [400, 500, 600, 700] },
  { pkg: "baloo-da-2", weights: [500, 600, 700, 800] },
  { pkg: "noto-sans-bengali", weights: [400, 600, 700, 800] },
  { pkg: "anek-bangla", weights: [400, 600, 700, 800] },
  { pkg: "inter", weights: [400, 500, 600, 700, 800] },
  { pkg: "baloo-2", weights: [600, 700, 800] },
  { pkg: "space-grotesk", weights: [500, 700] },
  // the typefaces the film styles name (design/styles, imported from lemo-opuscar); missing weights are skipped
  ...["ibm-plex-mono", "fredoka", "caveat", "barlow-condensed", "lilita-one", "jost", "inter-tight", "dm-mono", "cormorant-garamond",
      "architects-daughter", "titan-one", "quicksand", "playfair-display", "outfit", "old-standard-tt", "league-spartan", "league-gothic",
      "josefin-sans", "jetbrains-mono", "im-fell-english", "fraunces", "dela-gothic-one", "bricolage-grotesque", "big-shoulders-display",
      "bagel-fat-one", "b612"].map((pkg) => ({ pkg, weights: [400, 700, 800], quiet: true })),
];
const KEEP = /-(bengali|latin|latin-ext)-\d+-normal/;

let css = "/* generated by renderer/scripts/build-fonts.mjs — all fonts are SIL OFL 1.1 */\n";
const licenses = [];

for (const { pkg, weights, quiet } of FAMILIES) {
  const dir = path.join(root, "node_modules", "@fontsource", pkg);
  if (!fs.existsSync(dir)) {
    console.warn("missing package", pkg);
    continue;
  }
  const meta = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  licenses.push(`${meta.name} ${meta.version} — ${meta.license}`);
  for (const w of weights) {
    const cssFile = path.join(dir, `${w}.css`);
    if (!fs.existsSync(cssFile)) {
      if (!quiet) console.warn("missing weight", pkg, w);
      continue;
    }
    const blocks = fs.readFileSync(cssFile, "utf8").split(/(?=\/\* )/);
    for (const block of blocks) {
      const name = (block.match(/^\/\* ([^*]+) \*\//) || [])[1];
      if (!name || !KEEP.test(name)) continue;
      const file = `${name}.woff2`;
      const src = path.join(dir, "files", file);
      if (!fs.existsSync(src)) continue;
      fs.copyFileSync(src, path.join(out, file));
      css += block
        .replace(/src: url\([^)]*\) format\('woff2'\), url\([^)]*\) format\('woff'\);/, `src: url(./${file}) format('woff2');`)
        .replace(/font-display: swap;/, "font-display: block;")
        .trim() + "\n\n";
    }
  }
}

fs.writeFileSync(path.join(out, "fonts.css"), css);
fs.writeFileSync(path.join(out, "LICENSES.txt"), licenses.join("\n") + "\n");
console.log("fonts written to", out, "-", fs.readdirSync(out).length, "files");
