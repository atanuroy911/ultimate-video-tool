"""The Engine Server: this computer's own models offered to another computer (docs/plans/PLAN-ENGINES-AND-SETUP.MD section 3.4).

    vt serve-engine --port 8790          # prints an address and a one-time pairing code
    (on the other computer) Engines -> "Another Video Tool computer" -> address + code

It speaks the capability contract the registry already knows: `/.well-known/vt-engine` lists what this computer can do, `/v1/voice/speak` speaks a sentence, `/v1/asr/transcribe`
listens to a recording. A key is handed out once, to whoever knows the pairing code, and every other route needs it. Nothing here exposes projects, files or settings.
"""
from __future__ import annotations

import hmac
import secrets
import tempfile
from pathlib import Path
from typing import Any, Optional

import httpx
from fastapi import APIRouter, Depends, FastAPI, File, Form, Header, HTTPException, Request, UploadFile
from fastapi.responses import FileResponse, StreamingResponse, HTMLResponse
from pydantic import BaseModel, Field

VERSION = "1"


class PairBody(BaseModel):
    code: str


class SpeakBody(BaseModel):
    text: str = Field(min_length=1, max_length=20000)
    engine: str = "kokoro"
    voice: str = ""
    rate: float = Field(default=1.0, ge=0.5, le=2.0)
    language: str = ""


def capabilities() -> list[str]:
    caps = ["voice.speak"]
    try:
        import faster_whisper  # noqa: F401

        caps.append("asr.transcribe")
    except ImportError:
        pass
    return caps


HOP = {"host", "connection", "keep-alive", "transfer-encoding", "te", "trailer", "upgrade", "proxy-authorization", "proxy-authenticate", "content-length"}
CAPABILITY_OF = {"ollama": "llm.chat", "comfy": "image.generate"}


def create_app(*, key: str = "", pairing_code: str = "", name: str = "", services: Optional[dict[str, str]] = None) -> FastAPI:
    """`key` is the secret that unlocks /v1; `pairing_code` can be traded for it once. Both are generated by the caller (the CLI).

    `services` ({"ollama": "http://127.0.0.1:11434", ...}) turns this into the hub's gateway: `/gw/<key>/<service>/<path>` is forwarded to that service on this computer, so the
    other computer needs one address and one key for everything and the services themselves stay on 127.0.0.1.
    """
    app = FastAPI(title="Video Tool Engine Server", docs_url=None, redoc_url=None)
    app.include_router(engine_router(new_state(key=key, pairing_code=pairing_code, name=name, services=services)))
    @app.get("/", response_class=HTMLResponse)
    def dashboard() -> str:
        return (Path(__file__).with_name("dashboard.html")).read_text(encoding="utf-8")
    return app


def new_state(*, key: str = "", pairing_code: str = "", name: str = "", services: Optional[dict[str, str]] = None) -> dict[str, Any]:
    """What the engine routes read on every request. A dict, so `vt server` can fill it in after the Studio app was imported."""
    return {"key": key, "code": pairing_code, "name": name or "Video Tool engine", "services": dict(services or {})}


def engine_router(state: dict[str, Any]) -> APIRouter:
    """The engine contract as routes, for the standalone engine app and for `vt server` (the Studio and the engine on one port)."""
    app = APIRouter()

    def local_admin(request: Request) -> None:
        forwarded = {"forwarded", "x-forwarded-for", "x-real-ip", "cf-connecting-ip"}
        if not request.client or request.client.host not in ("127.0.0.1", "::1", "localhost") or any(h in request.headers for h in forwarded):
            raise HTTPException(403, "Open this page on the server computer to manage it.")

    @app.get("/v1/admin/status", dependencies=[Depends(local_admin)])
    def admin_status() -> dict[str, Any]:
        from . import hub
        return {"name": state["name"], "services": {n: hub.reachable(n, u, 1.0) for n, u in state["services"].items()}}

    def auth(authorization: Optional[str] = Header(default=None)) -> None:
        got = (authorization or "").removeprefix("Bearer ").strip()
        if not state["key"] or not hmac.compare_digest(got, state["key"]):
            raise HTTPException(401, "This engine needs its key. Pair with the code shown where it was started.")

    @app.get("/.well-known/vt-engine")
    def well_known() -> dict[str, Any]:
        return {"engine_server": VERSION, "name": state["name"], "capabilities": capabilities(), "needs_pairing": bool(state["code"]), "needs_key": True, "services": sorted(state["services"])}

    @app.post("/v1/pair")
    def pair(body: PairBody) -> dict[str, Any]:
        if not state["code"] or not hmac.compare_digest(body.code.strip(), state["code"]):
            raise HTTPException(403, "That pairing code is not right, or it was already used.")
        state["code"] = ""                                   # one use
        return {"key": state["key"], "services": {n: f"/gw/{state['key']}/{n}" for n in state["services"]}}

    @app.get("/v1/health", dependencies=[Depends(auth)])
    def health() -> dict[str, Any]:
        from . import hub

        up = {n: hub.reachable(n, u, 1.0) for n, u in state["services"].items()}
        caps = capabilities() + [CAPABILITY_OF[n] for n, ok in up.items() if ok and n in CAPABILITY_OF]
        return {"ok": True, "capabilities": sorted(set(caps)), "version": VERSION, "services": up}

    @app.post("/v1/admin/new-code", dependencies=[Depends(local_admin)])
    def new_code(request: Request) -> dict[str, str]:
        """A fresh pairing code. Only the computer the hub runs on may ask (`vt engine pair`)."""
        host = request.client.host if request.client else ""
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise HTTPException(403, "Ask for a pairing code on the computer that runs the engine: `vt engine pair`.")
        from . import hub

        state["code"] = hub.new_code()
        return {"code": state["code"]}

    @app.api_route("/gw/{gate}/{service}/{path:path}", methods=["GET", "POST", "PUT", "DELETE", "HEAD", "PATCH"])
    async def gateway(gate: str, service: str, path: str, request: Request) -> StreamingResponse:
        if not state["key"] or not hmac.compare_digest(gate, state["key"]):
            raise HTTPException(401, "This engine needs its key. Pair again.")
        if service not in state["services"]:
            raise HTTPException(404, f"This computer does not offer '{service}'.")
        url = state["services"][service].rstrip("/") + "/" + path
        headers = {k: v for k, v in request.headers.items() if k.lower() not in HOP}
        client = httpx.AsyncClient(timeout=httpx.Timeout(None, connect=10))
        try:
            upstream = await client.send(client.build_request(request.method, url, params=request.query_params, headers=headers, content=request.stream()), stream=True)
        except httpx.HTTPError as e:
            await client.aclose()
            raise HTTPException(502, f"{service} on this computer does not answer ({type(e).__name__}).")

        async def close() -> None:
            await upstream.aclose()
            await client.aclose()

        from starlette.background import BackgroundTask

        return StreamingResponse(upstream.aiter_raw(), status_code=upstream.status_code, headers={k: v for k, v in upstream.headers.items() if k.lower() not in HOP},
                                 background=BackgroundTask(close))

    @app.get("/v1/voice/list", dependencies=[Depends(auth)])
    def voice_list() -> dict[str, Any]:
        """Every voice this computer can speak with, as "<engine>:<voice>" (the form the caller sends back)."""
        from .. import tts

        out = []
        for e in tts.list_engines():
            if e["id"] in ("vtengine", "voicestudio", "clone") or not e.get("available", True):
                continue
            out += [{"id": f"{e['id']}:{v['id']}", "label": f"{e['label'].split(' (')[0]}: {v.get('label', v['id'])}", "lang": v.get("lang", "en")} for v in e["voices"]]
        return {"voices": out}

    @app.post("/v1/voice/speak", dependencies=[Depends(auth)])
    def speak(body: SpeakBody) -> FileResponse:
        from .. import tts

        out = Path(tempfile.mkdtemp(prefix="vt-engine-")) / "speech.wav"
        try:
            voice = body.voice or next((v["id"] for e in tts.list_engines() if e["id"] == body.engine for v in e["voices"]), "")
            tts.synthesize(body.text, out, engine=body.engine, voice=voice, rate=body.rate, language=body.language)
        except Exception as e:                               # noqa: BLE001 - the caller gets the reason, in a sentence
            raise HTTPException(422, f"Could not speak that: {type(e).__name__}: {str(e)[:200]}")
        return FileResponse(out, media_type="audio/wav", filename="speech.wav")

    @app.post("/v1/asr/transcribe", dependencies=[Depends(auth)])
    async def transcribe(audio: UploadFile = File(...), language: str = Form("en"), model: str = Form("")) -> dict[str, Any]:
        from ..stages import asr

        d = Path(tempfile.mkdtemp(prefix="vt-engine-"))
        src = d / (audio.filename or "audio.wav")
        src.write_bytes(await audio.read())
        try:
            return asr.transcribe(src, model=model or asr.model_for_language("", language), language=language)
        except Exception as e:                               # noqa: BLE001
            raise HTTPException(422, f"Could not listen to that: {type(e).__name__}: {str(e)[:200]}")

    return app


def new_secrets() -> tuple[str, str]:
    """(key, pairing code): the key is long and never typed; the code is short enough to read out."""
    return secrets.token_urlsafe(32), "-".join(secrets.token_hex(2) for _ in range(3))
