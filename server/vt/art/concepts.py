def gravity() -> str:
    arr = "".join(f'<path d="M{x} 18 L{x} 52" stroke="#a5b4fc" stroke-width="5" stroke-linecap="round"/><path d="M{x - 7} 44 L{x} 54 L{x + 7} 44" fill="none" stroke="#a5b4fc" stroke-width="5" stroke-linecap="round" stroke-linejoin="round"/>' for x in (28, 64, 100))
    return (f'<svg {V}>{arr}<path d="M4 112Q64 70 124 112" fill="#2563eb"/><path d="M4 112Q64 70 124 112" fill="none" stroke="#60a5fa" stroke-width="4"/>'
            '<circle cx="64" cy="64" r="9" fill="#ef4444"/><path d="M64 50q4-8 9-6" stroke="#22c55e" stroke-width="3" fill="none" stroke-linecap="round"/></svg>')


def eclipse() -> str:
    corona = "".join(f'<path d="M64 64L{64 + 60 * math.cos(math.radians(a)):.1f} {64 + 60 * math.sin(math.radians(a)):.1f}" stroke="#fde68a" stroke-width="3" opacity=".7" stroke-linecap="round"/>' for a in range(0, 360, 30))
    return f'<svg {V}>' + _space_disc("#10152f", "#04050c") + corona + '<circle cx="64" cy="64" r="32" fill="#fff3b0" opacity=".9"/><circle cx="64" cy="64" r="29" fill="#050505"/></svg>'


