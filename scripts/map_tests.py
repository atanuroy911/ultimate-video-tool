"""Which tests touch which source file? Generated from the code, so it cannot drift from it.

    python scripts/map_tests.py            # writes docs/evidence/code-test-map.md

A test file "covers" a source module when it imports it (`vt.x`, `from vt.x import`, `from vt import x`) or names its path.
A source file with no test file is listed as UNTESTED: it is exercised only indirectly, if at all.
"""
from __future__ import annotations

import ast
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "evidence" / "code-test-map.md"


def source_modules() -> dict[str, Path]:
    mods = {}
    for p in sorted((ROOT / "vt").rglob("*.py")):
        if "__pycache__" in p.parts:
            continue
        rel = p.relative_to(ROOT).with_suffix("")
        name = ".".join(rel.parts)
        mods[name[: -len(".__init__")] if name.endswith(".__init__") else name] = p
    return mods


def test_files() -> dict[str, dict]:
    out = {}
    for p in sorted((ROOT / "tests").glob("test_*.py")):
        src = p.read_text(encoding="utf-8", errors="replace")
        try:
            tree = ast.parse(src)
        except SyntaxError:
            continue
        tests = [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name.startswith("test_")]
        slow = "pytest.mark.slow" in src or "pytestmark = pytest.mark.slow" in src
        out[p.name] = {"src": src, "count": len(tests), "slow": slow}
    return out


def main() -> None:
    mods, tests = source_modules(), test_files()
    covered: dict[str, list[str]] = defaultdict(list)
    for tname, t in tests.items():
        src = t["src"]
        for mod in mods:
            short = mod.split(".", 1)[1] if "." in mod else mod
            patterns = [rf"\b{re.escape(mod)}\b", rf"from vt import [^\n]*\b{re.escape(short.split('.')[-1])}\b", rf"from vt\.{re.escape(short.rsplit('.', 1)[0])} import [^\n]*\b{re.escape(short.split('.')[-1])}\b" if "." in short else r"$^"]
            if any(re.search(p, src) for p in patterns) or str(mods[mod].relative_to(ROOT)).replace("\\", "/") in src:
                covered[mod].append(tname)
    lines = ["# Which tests touch which source file", "", "Generated by `scripts/map_tests.py` from imports and path mentions. A file marked **UNTESTED** is exercised only indirectly, if at all.", "",
             f"{len(mods)} source modules; {len(tests)} test files with {sum(t['count'] for t in tests.values())} test functions "
             f"({sum(t['count'] for t in tests.values() if t['slow'])} in files marked slow).", "", "| Source file | Lines | Test files |", "|---|---:|---|"]
    untested = []
    for mod, p in mods.items():
        n = len(p.read_text(encoding="utf-8", errors="replace").splitlines())
        names = covered.get(mod, [])
        if not names:
            untested.append((mod, p, n))
        rel = str(p.relative_to(ROOT)).replace("\\", "/")
        lines.append(f"| `{rel}` | {n} | " + (", ".join(f"`tests/{x}` ({tests[x]['count']}{', slow' if tests[x]['slow'] else ''})" for x in names) if names else "**UNTESTED**") + " |")
    lines += ["", f"## Untested source files ({len(untested)})", ""]
    lines += [f"* `{str(p.relative_to(ROOT)).replace(chr(92), '/')}` ({n} lines)" for _, p, n in untested]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(mods)} modules, {len(untested)} with no test file")


if __name__ == "__main__":
    main()
